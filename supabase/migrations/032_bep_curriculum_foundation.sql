-- ===================== Kaynak kapsamı (sürüm/sınıf/tema karışmasını önler) =====================
CREATE OR REPLACE FUNCTION public.curriculum_guard_source_scope() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_TABLE_NAME = 'curriculum_themes' THEN
   IF NOT EXISTS (SELECT 1 FROM public.curriculum_source_documents d JOIN public.curriculum_grades g ON g.id = NEW.grade_id
      WHERE d.id = NEW.source_document_id AND d.version_id = NEW.version_id AND d.doc_type IN ('theme_page','theme_pdf')
        AND d.grade = g.grade AND (d.theme_no IS NULL OR d.theme_no = NEW.theme_no)) THEN
     RAISE EXCEPTION 'Theme source scope mismatch'; END IF;
 ELSIF TG_TABLE_NAME = 'curriculum_outcomes' THEN
   IF NOT EXISTS (SELECT 1 FROM public.curriculum_source_documents d
      WHERE d.id = NEW.source_document_id AND d.version_id = NEW.version_id AND d.doc_type = 'main_program') THEN
     RAISE EXCEPTION 'Canonical outcome must cite main program'; END IF;
 ELSIF TG_TABLE_NAME = 'curriculum_components' THEN
   IF NOT EXISTS (SELECT 1 FROM public.curriculum_outcomes o JOIN public.curriculum_source_documents d ON d.id = NEW.source_document_id
      WHERE o.id = NEW.outcome_id AND d.version_id = o.version_id) THEN
     RAISE EXCEPTION 'Component source version mismatch'; END IF;
   IF EXISTS (SELECT 1 FROM public.curriculum_source_documents d WHERE d.id = NEW.source_document_id AND d.doc_type <> 'theme_page')
      AND NEW.source_page IS NULL THEN RAISE EXCEPTION 'PDF component source requires page'; END IF;
 ELSIF TG_TABLE_NAME = 'curriculum_theme_outcomes' THEN
   IF NOT EXISTS (SELECT 1 FROM public.curriculum_themes t
      JOIN public.curriculum_grades g ON g.id = t.grade_id
      JOIN public.curriculum_import_rows r ON r.id = NEW.import_row_id
      JOIN public.curriculum_import_batches b ON b.id = r.batch_id
      WHERE t.id = NEW.theme_id AND t.grade_id = NEW.grade_id AND t.version_id = NEW.version_id
        AND t.source_document_id = NEW.source_document_id
        AND b.version_id = NEW.version_id AND r.grade = g.grade AND r.theme_no = t.theme_no) THEN
     RAISE EXCEPTION 'Theme outcome source/grade/row scope mismatch'; END IF;
 ELSIF TG_TABLE_NAME = 'curriculum_theme_components' THEN
   IF NOT EXISTS (SELECT 1 FROM public.curriculum_import_rows r
      JOIN public.curriculum_import_batches b ON b.id = r.batch_id
      JOIN public.curriculum_theme_outcomes t ON t.id = NEW.theme_outcome_id
      JOIN public.curriculum_grades g ON g.id = t.grade_id
      JOIN public.curriculum_themes th ON th.id = t.theme_id
      WHERE r.id = NEW.import_row_id AND b.version_id = t.version_id AND r.grade = g.grade
        AND r.theme_no = th.theme_no AND t.theme_id = NEW.theme_id) THEN
     RAISE EXCEPTION 'Theme component import row scope mismatch'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER curriculum_theme_source_scope BEFORE INSERT ON public.curriculum_themes FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_source_scope();
CREATE TRIGGER curriculum_outcome_source_scope BEFORE INSERT ON public.curriculum_outcomes FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_source_scope();
CREATE TRIGGER curriculum_component_source_scope BEFORE INSERT ON public.curriculum_components FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_source_scope();
CREATE TRIGGER curriculum_theme_outcome_source_scope BEFORE INSERT ON public.curriculum_theme_outcomes FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_source_scope();
CREATE TRIGGER curriculum_theme_component_source_scope BEFORE INSERT ON public.curriculum_theme_components FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_source_scope();

-- ===================== Ders ve beceri alanı koruması =====================
CREATE OR REPLACE FUNCTION public.curriculum_guard_reference() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_TABLE_NAME = 'curriculum_subjects' THEN
   IF TG_OP = 'UPDATE' AND NEW.code IS DISTINCT FROM OLD.code THEN RAISE EXCEPTION 'Subject code immutable'; END IF;
   RETURN COALESCE(NEW, OLD);
 END IF;
 IF EXISTS (SELECT 1 FROM public.curriculum_grades WHERE version_id = OLD.version_id AND status IN ('published','retired')) THEN
   RAISE EXCEPTION 'Learning areas locked after publishing'; END IF;
 IF TG_OP = 'UPDATE' AND NEW.version_id IS DISTINCT FROM OLD.version_id THEN RAISE EXCEPTION 'Learning area version immutable'; END IF;
 RETURN COALESCE(NEW, OLD);
END $$;
