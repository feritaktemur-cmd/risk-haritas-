-- ===================== Sınıf yayın kapısı =====================
CREATE OR REPLACE FUNCTION public.curriculum_guard_grade_transition() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE version_state text; authority text; errs integer; expected_rows integer; actual_rows integer;
BEGIN
 IF TG_OP = 'INSERT' THEN
   IF NEW.status <> 'draft' OR NEW.published_at IS NOT NULL OR NEW.retired_at IS NOT NULL
      OR NEW.expected_outcome_count IS NOT NULL OR NEW.expected_theme_count IS NOT NULL THEN RAISE EXCEPTION 'New grade must be draft'; END IF;
   IF EXISTS (SELECT 1 FROM public.curriculum_versions WHERE id = NEW.version_id AND status = 'retired') THEN RAISE EXCEPTION 'Version retired'; END IF;
   RETURN NEW;
 END IF;
 IF (NEW.version_id, NEW.subject_id, NEW.grade) IS DISTINCT FROM (OLD.version_id, OLD.subject_id, OLD.grade) THEN
   RAISE EXCEPTION 'Grade identity immutable'; END IF;
 IF OLD.status IN ('published','retired') AND NEW.status = OLD.status THEN
   IF NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION 'Published grade immutable'; END IF;
   RETURN NEW;
 END IF;
 IF NEW.status IS DISTINCT FROM OLD.status AND NOT (
    (OLD.status = 'draft' AND NEW.status = 'in_review') OR
    (OLD.status = 'in_review' AND NEW.status IN ('draft','published')) OR
    (OLD.status = 'published' AND NEW.status = 'retired')) THEN
   RAISE EXCEPTION 'Invalid grade transition'; END IF;

 IF OLD.status = 'published' AND NEW.status = 'retired' THEN
   IF (NEW.import_batch_id, NEW.publish_note, NEW.published_at, NEW.expected_outcome_count, NEW.expected_outcome_count_decision_id, NEW.expected_theme_count, NEW.expected_theme_count_decision_id)
      IS DISTINCT FROM (OLD.import_batch_id, OLD.publish_note, OLD.published_at, OLD.expected_outcome_count, OLD.expected_outcome_count_decision_id, OLD.expected_theme_count, OLD.expected_theme_count_decision_id) THEN
     RAISE EXCEPTION 'Retirement cannot edit published grade metadata'; END IF;
   NEW.retired_at := now(); RETURN NEW;
 END IF;

 -- Beklenen sayılar: değer, aynı sınıfa ait ve aynı değeri taşıyan doğru türde kararla birebir eşleşmeli.
 IF NEW.expected_outcome_count IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d
    WHERE d.id = NEW.expected_outcome_count_decision_id AND d.grade_id = NEW.id
      AND d.decision = 'set_expected_outcome_count' AND d.expected_count = NEW.expected_outcome_count) THEN
   RAISE EXCEPTION 'Expected outcome count requires matching decision'; END IF;
 IF NEW.expected_theme_count IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d
    WHERE d.id = NEW.expected_theme_count_decision_id AND d.grade_id = NEW.id
      AND d.decision = 'set_expected_theme_count' AND d.expected_count = NEW.expected_theme_count) THEN
   RAISE EXCEPTION 'Expected theme count requires matching decision'; END IF;

 IF NEW.status IN ('draft','in_review') THEN
   IF NEW.published_at IS NOT NULL OR NEW.retired_at IS NOT NULL THEN RAISE EXCEPTION 'Publication timestamps are system-managed'; END IF;
   IF NEW.status = 'in_review' AND OLD.status = 'draft'
      AND EXISTS (SELECT 1 FROM public.curriculum_versions WHERE id = NEW.version_id AND status = 'retired') THEN
     RAISE EXCEPTION 'Version retired'; END IF;
   RETURN NEW;
 END IF;

 -- in_review -> published
 SELECT status, component_authority INTO version_state, authority FROM public.curriculum_versions WHERE id = NEW.version_id FOR UPDATE;
 IF version_state <> 'active' THEN RAISE EXCEPTION 'Version not active'; END IF;
 IF authority IS NULL THEN RAISE EXCEPTION 'Component authority not set'; END IF;
 IF NEW.import_batch_id IS NULL OR nullif(btrim(NEW.publish_note), '') IS NULL THEN RAISE EXCEPTION 'Missing import batch or publish note'; END IF;
 SELECT error_count, row_count INTO errs, expected_rows FROM public.curriculum_import_batches WHERE id = NEW.import_batch_id AND version_id = NEW.version_id;
 IF errs IS NULL OR errs <> 0 THEN RAISE EXCEPTION 'Import validation errors'; END IF;
 SELECT count(*) INTO actual_rows FROM public.curriculum_import_rows WHERE batch_id = NEW.import_batch_id;
 IF actual_rows <> expected_rows THEN RAISE EXCEPTION 'Import row count mismatch'; END IF;
 IF EXISTS (SELECT 1 FROM public.curriculum_import_rows r WHERE r.batch_id = NEW.import_batch_id AND r.grade = NEW.grade AND r.row_status = 'error') THEN
   RAISE EXCEPTION 'Import row errors'; END IF;
 IF NOT EXISTS (SELECT 1 FROM public.curriculum_themes WHERE grade_id = NEW.id)
    OR NOT EXISTS (SELECT 1 FROM public.curriculum_outcomes WHERE grade_id = NEW.id) THEN
   RAISE EXCEPTION 'Missing themes or outcomes'; END IF;
 IF EXISTS (SELECT 1 FROM public.curriculum_outcomes o WHERE o.grade_id = NEW.id AND (
      o.verification_status <> 'verified' OR o.component_structure IS NULL
   OR (o.component_structure = 'has_components' AND NOT EXISTS (SELECT 1 FROM public.curriculum_components c WHERE c.outcome_id = o.id))
   OR (o.component_structure = 'no_components_confirmed' AND EXISTS (SELECT 1 FROM public.curriculum_components c WHERE c.outcome_id = o.id)))) THEN
   RAISE EXCEPTION 'Unverified or structurally incomplete outcomes'; END IF;
 IF EXISTS (SELECT 1 FROM public.curriculum_components c JOIN public.curriculum_outcomes o ON o.id = c.outcome_id
    WHERE o.grade_id = NEW.id AND c.verification_status <> 'verified') THEN
   RAISE EXCEPTION 'Unverified components'; END IF;
 -- Bileşen kaynağı ve doğrulama kanıtı sürümün bileşen yetkisiyle uyumlu olmalı
 IF EXISTS (SELECT 1 FROM public.curriculum_components c
    JOIN public.curriculum_outcomes o ON o.id = c.outcome_id
    JOIN public.curriculum_source_documents sd ON sd.id = c.source_document_id
    JOIN public.curriculum_review_decisions d ON d.id = c.verification_decision_id
    JOIN public.curriculum_source_documents ed ON ed.id = d.source_document_id
    WHERE o.grade_id = NEW.id AND (
      (authority = 'main_program' AND (sd.doc_type <> 'main_program' OR ed.doc_type <> 'main_program'))
   OR (authority = 'theme_sources' AND (sd.doc_type = 'main_program' OR ed.doc_type = 'main_program')))) THEN
   RAISE EXCEPTION 'Component evidence does not match component authority'; END IF;
 IF EXISTS (SELECT 1 FROM public.curriculum_theme_outcomes WHERE grade_id = NEW.id AND mapping_status NOT IN ('verified','excluded')) THEN
   RAISE EXCEPTION 'Unresolved theme outcomes'; END IF;
 IF EXISTS (SELECT 1 FROM public.curriculum_theme_components c JOIN public.curriculum_theme_outcomes o ON o.id = c.theme_outcome_id
    WHERE o.grade_id = NEW.id AND c.mapping_status NOT IN ('verified','excluded')) THEN
   RAISE EXCEPTION 'Unresolved theme components'; END IF;
 -- A: partide sınıfı/teması belirsiz satır olmamalı; sınıfa ait en az bir satır bulunmalı ve hiçbiri işlenmeden kalmamalı
 IF EXISTS (SELECT 1 FROM public.curriculum_import_rows r WHERE r.batch_id = NEW.import_batch_id AND (r.grade IS NULL OR r.theme_no IS NULL)) THEN
   RAISE EXCEPTION 'Import batch has rows without grade/theme'; END IF;
 IF NOT EXISTS (SELECT 1 FROM public.curriculum_import_rows r WHERE r.batch_id = NEW.import_batch_id AND r.grade = NEW.grade) THEN
   RAISE EXCEPTION 'Import batch has no rows for this grade'; END IF;
 -- B: tüm tema kayıtları yayın için seçilen aynı partiden gelmeli
 IF EXISTS (SELECT 1 FROM public.curriculum_theme_outcomes t JOIN public.curriculum_import_rows r ON r.id = t.import_row_id
    WHERE t.grade_id = NEW.id AND r.batch_id <> NEW.import_batch_id)
    OR EXISTS (SELECT 1 FROM public.curriculum_theme_components c
    JOIN public.curriculum_theme_outcomes t ON t.id = c.theme_outcome_id
    JOIN public.curriculum_import_rows r ON r.id = c.import_row_id
    WHERE t.grade_id = NEW.id AND r.batch_id <> NEW.import_batch_id) THEN
   RAISE EXCEPTION 'Theme records from a different import batch'; END IF;
 -- A (devam): hiçbir ham satır işlenmeden kalmamalı
 IF EXISTS (SELECT 1 FROM public.curriculum_import_rows r
    WHERE r.batch_id = NEW.import_batch_id AND r.grade = NEW.grade
      AND NOT EXISTS (SELECT 1 FROM public.curriculum_theme_components c WHERE c.import_row_id = r.id)
      AND NOT (r.published_label IS NULL AND EXISTS (SELECT 1 FROM public.curriculum_theme_outcomes t WHERE t.import_row_id = r.id))) THEN
   RAISE EXCEPTION 'Unprocessed import rows for this grade'; END IF;
 -- D: beklenen sayılar zorunlu ve gerçek sayılarla birebir uyumlu olmalı
 IF NEW.expected_outcome_count IS NULL OR NEW.expected_theme_count IS NULL THEN
   RAISE EXCEPTION 'Expected outcome/theme counts not set'; END IF;
 IF (SELECT count(*) FROM public.curriculum_outcomes WHERE grade_id = NEW.id) <> NEW.expected_outcome_count THEN
   RAISE EXCEPTION 'Outcome count does not match expected count'; END IF;
 IF (SELECT count(*) FROM public.curriculum_themes WHERE grade_id = NEW.id) <> NEW.expected_theme_count THEN
   RAISE EXCEPTION 'Theme count does not match expected count'; END IF;
 NEW.published_at := now();
 NEW.retired_at := NULL;
 RETURN NEW;
END $$;
CREATE TRIGGER curriculum_grade_transition BEFORE INSERT OR UPDATE ON public.curriculum_grades FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_grade_transition();
CREATE OR REPLACE FUNCTION public.curriculum_guard_grade_delete() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
 IF OLD.status IN ('published','retired') THEN RAISE EXCEPTION 'Published/retired grade cannot be deleted'; END IF;
 RETURN OLD;
END $$;
CREATE TRIGGER curriculum_grades_no_delete BEFORE DELETE ON public.curriculum_grades FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_grade_delete();

-- ===================== Sürüm durum geçişleri =====================
CREATE OR REPLACE FUNCTION public.curriculum_guard_version_transition() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_OP = 'DELETE' THEN
   IF OLD.status <> 'draft' THEN RAISE EXCEPTION 'Only draft versions can be deleted'; END IF;
   RETURN OLD;
 END IF;
 IF TG_OP = 'INSERT' THEN
   IF NEW.status <> 'draft' OR NEW.component_authority IS NOT NULL OR NEW.activated_at IS NOT NULL OR NEW.retired_at IS NOT NULL THEN
     RAISE EXCEPTION 'New version must be draft without authority'; END IF;
   RETURN NEW;
 END IF;
 IF (NEW.subject_id, NEW.version_code, NEW.title) IS DISTINCT FROM (OLD.subject_id, OLD.version_code, OLD.title) THEN
   RAISE EXCEPTION 'Version identity immutable'; END IF;
 IF OLD.status = 'retired' AND NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION 'Retired version immutable'; END IF;
 IF (NEW.component_authority, NEW.component_authority_decision_id) IS DISTINCT FROM (OLD.component_authority, OLD.component_authority_decision_id) THEN
   IF OLD.component_authority IS NOT NULL THEN RAISE EXCEPTION 'Component authority already set'; END IF;
   IF NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d
      JOIN public.curriculum_source_documents s ON s.id = d.source_document_id
      WHERE d.id = NEW.component_authority_decision_id AND d.version_id = NEW.id AND d.decision = 'set_component_authority'
        AND d.authority_value = NEW.component_authority AND s.doc_type = 'main_program') THEN
     RAISE EXCEPTION 'Component authority requires evidence'; END IF;
 END IF;
 IF NEW.status IS DISTINCT FROM OLD.status THEN
   IF OLD.status = 'draft' AND NEW.status = 'active' THEN
     IF NOT EXISTS (SELECT 1 FROM public.curriculum_source_documents WHERE version_id = NEW.id AND doc_type = 'main_program') THEN
       RAISE EXCEPTION 'Main program evidence required'; END IF;
     NEW.activated_at := now();
   ELSIF OLD.status = 'active' AND NEW.status = 'retired' THEN
     IF EXISTS (SELECT 1 FROM public.curriculum_grades WHERE version_id = NEW.id AND status IN ('published','in_review')) THEN
       RAISE EXCEPTION 'All published grades must retire first'; END IF;
     NEW.retired_at := now();
   ELSE RAISE EXCEPTION 'Invalid version transition'; END IF;
 ELSIF (NEW.activated_at, NEW.retired_at) IS DISTINCT FROM (OLD.activated_at, OLD.retired_at) THEN
   RAISE EXCEPTION 'Version timestamps are system-managed';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER curriculum_version_transition BEFORE INSERT OR UPDATE OR DELETE ON public.curriculum_versions
 FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_version_transition();

-- ===================== Öğretmen kataloğu (yalnızca yayımlanmış + doğrulanmış) =====================
CREATE VIEW public.curriculum_teacher_catalog WITH (security_invoker = true) AS
SELECT v.subject_id, v.id AS version_id, v.version_code, g.id AS grade_id, g.grade,
       la.id AS learning_area_id, la.official_code AS learning_area_code, la.official_name AS learning_area_name, la.sort_order AS learning_area_sort,
       o.id AS outcome_id, o.canonical_code, o.canonical_text AS outcome_text, o.sort_order AS outcome_sort, o.component_structure,
       c.id AS component_id, c.canonical_label, c.canonical_text AS component_text, c.sort_order AS component_sort,
       COALESCE((SELECT array_agg(DISTINCT th.theme_no ORDER BY th.theme_no)
                   FROM public.curriculum_theme_components tc JOIN public.curriculum_themes th ON th.id = tc.theme_id
                  WHERE tc.component_id = c.id AND tc.mapping_status = 'verified'),
                (SELECT array_agg(DISTINCT th.theme_no ORDER BY th.theme_no)
                   FROM public.curriculum_theme_outcomes t JOIN public.curriculum_themes th ON th.id = t.theme_id
                  WHERE c.id IS NULL AND t.outcome_id = o.id AND t.mapping_status = 'verified'),
                '{}'::smallint[]) AS theme_nos
  FROM public.curriculum_grades g
  JOIN public.curriculum_versions v ON v.id = g.version_id AND v.status = 'active'
  JOIN public.curriculum_outcomes o ON o.grade_id = g.id AND o.verification_status = 'verified'
  JOIN public.curriculum_learning_areas la ON la.id = o.learning_area_id
  LEFT JOIN public.curriculum_components c ON c.outcome_id = o.id AND c.verification_status = 'verified'
 WHERE g.status = 'published';

