-- 032_bep_curriculum_foundation.sql
-- PDRPUSULA / BEP merkezi müfredat temeli (13 tablo). Yalnızca yeni curriculum_* nesneleri oluşturur.
-- Mevcut tablolara dokunmaz, veri/seed içermez. V3 REVIEW dosyası temel alınmıştır.
-- Kanonik kayıtlar ana programdan; tema kayıtları kaynakta yayımlandığı gibi (aynen) saklanır.
-- Eşleştirme/doğrulama yalnızca kanıtlı karar kaydıyla; yayın sınıf bazındadır.
-- TEKNİK NOT (C — kaynak dosya bütünlüğü): Bu migration CSV dosyasının kendisini göremez.
--   İleride geliştirilecek CSV aktarımı, curriculum_import_batches.file_sha256 ve row_count
--   değerlerini aktarım aracının beyanına değil, gerçek kaynak dosyadan bağımsız olarak hesaplamalı;
--   import_rows.raw_sha256 her satır için ayrıca hesaplanmalı ve doğrulama raporunda karşılaştırılmalıdır.
BEGIN;

-- 1. Dersler
CREATE TABLE public.curriculum_subjects (
 id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code text NOT NULL UNIQUE CHECK (length(btrim(code)) > 0),
 name text NOT NULL CHECK (length(btrim(name)) > 0),
 sort_order integer NOT NULL DEFAULT 0,
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now()
);

-- 2. Müfredat sürümleri
CREATE TABLE public.curriculum_versions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 subject_id smallint NOT NULL REFERENCES public.curriculum_subjects(id) ON DELETE RESTRICT,
 version_code text NOT NULL CHECK (length(btrim(version_code)) > 0),
 title text NOT NULL CHECK (length(btrim(title)) > 0),
 notes text,
 status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','retired')),
 component_authority text CHECK (component_authority IN ('main_program','theme_sources')),
 component_authority_decision_id uuid,
 activated_at timestamptz, retired_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (subject_id, version_code), UNIQUE (id, subject_id),
 CHECK ((component_authority IS NULL) = (component_authority_decision_id IS NULL))
);

-- 3. Kaynak belgeler (ana program PDF, tema sayfası, tema PDF)
CREATE TABLE public.curriculum_source_documents (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 version_id uuid NOT NULL REFERENCES public.curriculum_versions(id) ON DELETE RESTRICT,
 doc_type text NOT NULL CHECK (doc_type IN ('main_program','theme_page','theme_pdf')),
 grade smallint CHECK (grade BETWEEN 1 AND 12),
 theme_no smallint CHECK (theme_no > 0),
 title text NOT NULL CHECK (length(btrim(title)) > 0),
 publisher text, url text, file_name text, file_sha256 text,
 published_at timestamptz, retrieved_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (id, version_id),
 CHECK (url IS NOT NULL OR file_sha256 IS NOT NULL),
 CHECK (doc_type = 'main_program' OR grade IS NOT NULL)
);
CREATE UNIQUE INDEX curriculum_doc_file_unique ON public.curriculum_source_documents(version_id, file_sha256) WHERE file_sha256 IS NOT NULL;
CREATE UNIQUE INDEX curriculum_doc_url_unique ON public.curriculum_source_documents(version_id, doc_type, url) WHERE url IS NOT NULL;

-- 11. Aktarım partileri
CREATE TABLE public.curriculum_import_batches (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 version_id uuid NOT NULL REFERENCES public.curriculum_versions(id) ON DELETE RESTRICT,
 file_name text NOT NULL, file_sha256 text NOT NULL,
 row_count integer NOT NULL CHECK (row_count >= 0),
 error_count integer NOT NULL DEFAULT 0 CHECK (error_count >= 0),
 warning_count integer NOT NULL DEFAULT 0 CHECK (warning_count >= 0),
 validation_report jsonb NOT NULL DEFAULT '{}'::jsonb,
 validator_version text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (version_id, file_sha256), UNIQUE (id, version_id)
);

-- 12. Ham kaynak satırları (değiştirilemez kanıt)
CREATE TABLE public.curriculum_import_rows (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 batch_id uuid NOT NULL REFERENCES public.curriculum_import_batches(id) ON DELETE RESTRICT,
 source_row_no integer NOT NULL CHECK (source_row_no > 0),
 raw_values jsonb NOT NULL CHECK (jsonb_typeof(raw_values) = 'object'),
 raw_sha256 text NOT NULL,
 grade smallint CHECK (grade BETWEEN 1 AND 12),
 theme_no smallint CHECK (theme_no > 0),
 published_code text, published_label text,
 row_status text NOT NULL CHECK (row_status IN ('ok','warning','error')),
 issues jsonb NOT NULL DEFAULT '[]'::jsonb,
 UNIQUE (batch_id, source_row_no)
);

-- 4. Sınıflar (yayın birimi)
CREATE TABLE public.curriculum_grades (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 version_id uuid NOT NULL, subject_id smallint NOT NULL,
 grade smallint NOT NULL CHECK (grade BETWEEN 1 AND 12),
 status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','in_review','published','retired')),
 import_batch_id uuid,
 published_at timestamptz, retired_at timestamptz, publish_note text,
 -- Beklenen sayılar yalnızca kanıtlı karar kaydıyla atanır (tahmin edilmez).
 expected_outcome_count integer CHECK (expected_outcome_count > 0), expected_outcome_count_decision_id uuid,
 expected_theme_count integer CHECK (expected_theme_count > 0), expected_theme_count_decision_id uuid,
 CHECK ((expected_outcome_count IS NULL) = (expected_outcome_count_decision_id IS NULL)),
 CHECK ((expected_theme_count IS NULL) = (expected_theme_count_decision_id IS NULL)),
 FOREIGN KEY (version_id, subject_id) REFERENCES public.curriculum_versions(id, subject_id) ON DELETE RESTRICT,
 FOREIGN KEY (import_batch_id, version_id) REFERENCES public.curriculum_import_batches(id, version_id) ON DELETE RESTRICT,
 UNIQUE (version_id, grade), UNIQUE (id, version_id)
);
CREATE UNIQUE INDEX curriculum_one_published_subject_grade ON public.curriculum_grades(subject_id, grade) WHERE status = 'published';

-- 5. Beceri alanları
CREATE TABLE public.curriculum_learning_areas (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 version_id uuid NOT NULL REFERENCES public.curriculum_versions(id) ON DELETE RESTRICT,
 official_code text NOT NULL, official_name text NOT NULL,
 sort_order integer NOT NULL DEFAULT 0,
 UNIQUE (version_id, official_code), UNIQUE (id, version_id)
);

-- 6. Temalar (yayımlandığı gibi)
CREATE TABLE public.curriculum_themes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 version_id uuid NOT NULL, grade_id uuid NOT NULL,
 theme_no smallint NOT NULL CHECK (theme_no > 0),
 published_name text NOT NULL,
 source_document_id uuid NOT NULL,
 sort_order integer NOT NULL DEFAULT 0,
 FOREIGN KEY (grade_id, version_id) REFERENCES public.curriculum_grades(id, version_id) ON DELETE RESTRICT,
 FOREIGN KEY (source_document_id, version_id) REFERENCES public.curriculum_source_documents(id, version_id) ON DELETE RESTRICT,
 UNIQUE (grade_id, theme_no), UNIQUE (id, grade_id)
);

-- 7. Kanonik kazanımlar (ana program)
CREATE TABLE public.curriculum_outcomes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 version_id uuid NOT NULL, grade_id uuid NOT NULL, learning_area_id uuid NOT NULL,
 canonical_code text NOT NULL, code_key text NOT NULL, canonical_text text NOT NULL,
 source_document_id uuid NOT NULL,
 source_page integer NOT NULL CHECK (source_page > 0),
 sort_order integer NOT NULL DEFAULT 0,
 verification_status text NOT NULL DEFAULT 'pending' CHECK (verification_status IN ('pending','verified')),
 verification_decision_id uuid,
 component_structure text CHECK (component_structure IN ('has_components','no_components_confirmed')),
 component_structure_decision_id uuid,
 FOREIGN KEY (grade_id, version_id) REFERENCES public.curriculum_grades(id, version_id) ON DELETE RESTRICT,
 FOREIGN KEY (learning_area_id, version_id) REFERENCES public.curriculum_learning_areas(id, version_id) ON DELETE RESTRICT,
 FOREIGN KEY (source_document_id, version_id) REFERENCES public.curriculum_source_documents(id, version_id) ON DELETE RESTRICT,
 UNIQUE (grade_id, code_key), UNIQUE (id, grade_id),
 CHECK ((verification_status = 'verified') = (verification_decision_id IS NOT NULL)),
 CHECK ((component_structure = 'no_components_confirmed') = (component_structure_decision_id IS NOT NULL))
);

-- 8. Kanonik süreç bileşenleri
CREATE TABLE public.curriculum_components (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 outcome_id uuid NOT NULL REFERENCES public.curriculum_outcomes(id) ON DELETE RESTRICT,
 canonical_label text NOT NULL, label_key text NOT NULL, canonical_text text NOT NULL,
 source_document_id uuid NOT NULL REFERENCES public.curriculum_source_documents(id) ON DELETE RESTRICT,
 source_page integer CHECK (source_page > 0),
 sort_order integer NOT NULL DEFAULT 0,
 verification_status text NOT NULL DEFAULT 'pending' CHECK (verification_status IN ('pending','verified')),
 verification_decision_id uuid,
 UNIQUE (outcome_id, label_key), UNIQUE (id, outcome_id),
 CHECK ((verification_status = 'verified') = (verification_decision_id IS NOT NULL))
);

-- 9. Tema kazanımları (aynen; kanonik eşleşme yalnızca kararla)
CREATE TABLE public.curriculum_theme_outcomes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 version_id uuid NOT NULL, grade_id uuid NOT NULL, theme_id uuid NOT NULL,
 published_code text NOT NULL, published_code_key text NOT NULL, published_text text NOT NULL,
 import_row_id uuid NOT NULL REFERENCES public.curriculum_import_rows(id) ON DELETE RESTRICT,
 source_field text NOT NULL,
 source_document_id uuid NOT NULL, source_page integer CHECK (source_page > 0),
 sort_order_in_theme integer NOT NULL DEFAULT 0,
 outcome_id uuid,
 mapping_status text NOT NULL DEFAULT 'unmapped' CHECK (mapping_status IN ('unmapped','conflict','verified','excluded')),
 mapping_decision_id uuid,
 FOREIGN KEY (theme_id, grade_id) REFERENCES public.curriculum_themes(id, grade_id) ON DELETE RESTRICT,
 FOREIGN KEY (grade_id, version_id) REFERENCES public.curriculum_grades(id, version_id) ON DELETE RESTRICT,
 FOREIGN KEY (source_document_id, version_id) REFERENCES public.curriculum_source_documents(id, version_id) ON DELETE RESTRICT,
 FOREIGN KEY (outcome_id, grade_id) REFERENCES public.curriculum_outcomes(id, grade_id) ON DELETE RESTRICT,
 UNIQUE (theme_id, published_code_key), UNIQUE (id, theme_id), UNIQUE (id, outcome_id),
 CHECK ((mapping_status = 'verified' AND outcome_id IS NOT NULL AND mapping_decision_id IS NOT NULL)
     OR (mapping_status = 'excluded' AND outcome_id IS NULL AND mapping_decision_id IS NOT NULL)
     OR (mapping_status IN ('unmapped','conflict') AND outcome_id IS NULL AND mapping_decision_id IS NULL))
);
CREATE UNIQUE INDEX curriculum_theme_outcome_canonical_unique ON public.curriculum_theme_outcomes(theme_id, outcome_id) WHERE outcome_id IS NOT NULL;

-- 10. Tema bileşenleri (aynen; birleşik satırlar karar kaydıyla tam alt dizgiye bölünür)
CREATE TABLE public.curriculum_theme_components (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 theme_outcome_id uuid NOT NULL, theme_id uuid NOT NULL,
 published_label text NOT NULL, published_label_key text NOT NULL, published_text text NOT NULL,
 source_page integer CHECK (source_page > 0),
 sort_order_in_theme integer NOT NULL DEFAULT 0,
 import_row_id uuid NOT NULL REFERENCES public.curriculum_import_rows(id) ON DELETE RESTRICT,
 source_field text NOT NULL,
 origin text NOT NULL DEFAULT 'source_row' CHECK (origin IN ('source_row','split_by_decision')),
 segment_no integer NOT NULL DEFAULT 1 CHECK (segment_no > 0),
 segment_start integer, segment_end integer, -- sıfır tabanlı, yarı açık karakter aralığı [start,end)
 split_decision_id uuid,
 excluded_by_parent boolean NOT NULL DEFAULT false,
 outcome_id uuid, component_id uuid,
 mapping_status text NOT NULL DEFAULT 'unmapped' CHECK (mapping_status IN ('unmapped','conflict','verified','excluded')),
 mapping_decision_id uuid,
 FOREIGN KEY (theme_outcome_id, theme_id) REFERENCES public.curriculum_theme_outcomes(id, theme_id) ON DELETE RESTRICT,
 FOREIGN KEY (component_id, outcome_id) REFERENCES public.curriculum_components(id, outcome_id) ON DELETE RESTRICT,
 UNIQUE (theme_outcome_id, published_label_key),
 UNIQUE (import_row_id, source_field, segment_no),
 CHECK ((origin = 'source_row' AND segment_no = 1 AND split_decision_id IS NULL AND segment_start IS NULL AND segment_end IS NULL)
     OR (origin = 'split_by_decision' AND split_decision_id IS NOT NULL AND segment_start >= 0 AND segment_end > segment_start)),
 CHECK ((mapping_status = 'verified' AND outcome_id IS NOT NULL AND component_id IS NOT NULL AND mapping_decision_id IS NOT NULL AND NOT excluded_by_parent)
     OR (mapping_status = 'excluded' AND outcome_id IS NULL AND component_id IS NULL AND (mapping_decision_id IS NOT NULL) <> excluded_by_parent)
     OR (mapping_status IN ('unmapped','conflict') AND outcome_id IS NULL AND component_id IS NULL AND mapping_decision_id IS NULL AND NOT excluded_by_parent))
);
-- Üst eşleşme değişirken zincirleme güncellemeye izin vermek için ertelenir; commit anında denetlenir.
ALTER TABLE public.curriculum_theme_components ADD CONSTRAINT curriculum_theme_component_parent_outcome_fk
