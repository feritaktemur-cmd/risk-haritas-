-- ===================== Karar koruması =====================
CREATE OR REPLACE FUNCTION public.curriculum_guard_decision() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE doc_kind text; g_state text; v_authority text;
BEGIN
 SELECT doc_type INTO doc_kind FROM public.curriculum_source_documents WHERE id = NEW.source_document_id AND version_id = NEW.version_id;
 IF doc_kind IS NULL THEN RAISE EXCEPTION 'Missing decision evidence document'; END IF;
 IF doc_kind <> 'theme_page' AND NEW.source_page IS NULL THEN RAISE EXCEPTION 'PDF evidence requires source_page'; END IF;
 SELECT component_authority INTO v_authority FROM public.curriculum_versions WHERE id = NEW.version_id;

 IF NEW.grade_id IS NOT NULL THEN
   SELECT status INTO g_state FROM public.curriculum_grades WHERE id = NEW.grade_id AND version_id = NEW.version_id;
   IF g_state IS NULL THEN RAISE EXCEPTION 'Decision grade/version mismatch'; END IF;
   IF g_state IN ('published','retired') THEN RAISE EXCEPTION 'Published/retired grade is frozen'; END IF;
 END IF;

 -- Kanonik kararlar ana program kanıtı ister; bileşen yetkisi tema kaynaklarıysa bileşen doğrulaması tema kaynağı ister.
 -- Beklenen kazanım sayısı ana programdan; tema sayısı ana programdan veya aynı sınıfın resmî tema kaynağından.
 IF NEW.decision = 'set_expected_theme_count' AND NOT (doc_kind = 'main_program' OR EXISTS (
    SELECT 1 FROM public.curriculum_source_documents d JOIN public.curriculum_grades g ON g.id = NEW.grade_id
     WHERE d.id = NEW.source_document_id AND d.doc_type IN ('theme_page','theme_pdf') AND d.grade = g.grade)) THEN
   RAISE EXCEPTION 'Expected theme count requires official grade source'; END IF;
 IF NEW.decision IN ('map_to_canonical','confirm_no_components','set_component_authority','set_expected_outcome_count')
    OR (NEW.decision = 'verify_canonical' AND NEW.outcome_id IS NOT NULL) THEN
   IF doc_kind <> 'main_program' THEN RAISE EXCEPTION 'Canonical decision requires main program evidence'; END IF;
 END IF;
 IF NEW.decision = 'verify_canonical' THEN
   IF num_nonnulls(NEW.outcome_id, NEW.component_id) <> 1 THEN RAISE EXCEPTION 'Verification target required'; END IF;
   IF NEW.component_id IS NOT NULL THEN
     IF v_authority IS NULL THEN RAISE EXCEPTION 'Component authority must be set before component verification'; END IF;
     IF (v_authority = 'main_program' AND doc_kind <> 'main_program')
        OR (v_authority = 'theme_sources' AND doc_kind NOT IN ('theme_page','theme_pdf')) THEN
       RAISE EXCEPTION 'Component evidence does not match component authority'; END IF;
   END IF;
 END IF;
 IF NEW.decision = 'confirm_no_components' THEN
   IF NEW.outcome_id IS NULL THEN RAISE EXCEPTION 'Outcome target required'; END IF;
   IF EXISTS (SELECT 1 FROM public.curriculum_components WHERE outcome_id = NEW.outcome_id) THEN RAISE EXCEPTION 'Outcome has components'; END IF;
 END IF;
 IF NEW.decision = 'map_to_canonical' AND NOT ((NEW.theme_outcome_id IS NOT NULL AND NEW.target_outcome_id IS NOT NULL)
     OR (NEW.theme_component_id IS NOT NULL AND NEW.target_component_id IS NOT NULL)) THEN
   RAISE EXCEPTION 'Mapping target type mismatch'; END IF;
 IF NEW.decision IN ('mark_conflict','exclude') AND NEW.theme_outcome_id IS NULL AND NEW.theme_component_id IS NULL THEN
   RAISE EXCEPTION 'Conflict/exclusion must target a theme record'; END IF;

 -- Kapsam: tüm hedefler aynı sürüm ve sınıfa ait olmalı
 IF NEW.theme_outcome_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_theme_outcomes
    WHERE id = NEW.theme_outcome_id AND version_id = NEW.version_id AND grade_id = NEW.grade_id) THEN
   RAISE EXCEPTION 'Decision theme outcome mismatch'; END IF;
 IF NEW.theme_component_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_theme_components c
    JOIN public.curriculum_theme_outcomes t ON t.id = c.theme_outcome_id
    WHERE c.id = NEW.theme_component_id AND t.version_id = NEW.version_id AND t.grade_id = NEW.grade_id) THEN
   RAISE EXCEPTION 'Decision theme component mismatch'; END IF;
 IF NEW.outcome_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_outcomes
    WHERE id = NEW.outcome_id AND version_id = NEW.version_id AND grade_id = NEW.grade_id) THEN
   RAISE EXCEPTION 'Decision outcome mismatch'; END IF;
 IF NEW.component_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_components c
    JOIN public.curriculum_outcomes o ON o.id = c.outcome_id
    WHERE c.id = NEW.component_id AND o.version_id = NEW.version_id AND o.grade_id = NEW.grade_id) THEN
   RAISE EXCEPTION 'Decision component mismatch'; END IF;
 IF NEW.target_outcome_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_outcomes
    WHERE id = NEW.target_outcome_id AND version_id = NEW.version_id AND grade_id = NEW.grade_id) THEN
   RAISE EXCEPTION 'Decision mapped outcome mismatch'; END IF;
 IF NEW.target_component_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_components c
    JOIN public.curriculum_outcomes o ON o.id = c.outcome_id
    WHERE c.id = NEW.target_component_id AND o.version_id = NEW.version_id AND o.grade_id = NEW.grade_id) THEN
   RAISE EXCEPTION 'Decision mapped component mismatch'; END IF;
 IF NEW.import_row_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.curriculum_import_rows r
    JOIN public.curriculum_import_batches b ON b.id = r.batch_id
    JOIN public.curriculum_grades g ON g.id = NEW.grade_id
    WHERE r.id = NEW.import_row_id AND b.version_id = NEW.version_id AND r.grade = g.grade) THEN
   RAISE EXCEPTION 'Decision import row mismatch'; END IF;
 -- Bileşen eşleşmesi: hedef bileşen, üst tema kazanımının eşlendiği kanonik kazanıma ait olmalı (sahiplik)
 IF NEW.decision = 'map_to_canonical' AND NEW.target_component_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.curriculum_theme_components tc
    JOIN public.curriculum_theme_outcomes t ON t.id = tc.theme_outcome_id
    JOIN public.curriculum_components c ON c.id = NEW.target_component_id
    WHERE tc.id = NEW.theme_component_id AND t.mapping_status = 'verified' AND t.outcome_id = c.outcome_id) THEN
   RAISE EXCEPTION 'Mapped component does not belong to mapped theme outcome'; END IF;
 IF NEW.decision = 'set_component_authority' AND EXISTS (SELECT 1 FROM public.curriculum_grades
    WHERE version_id = NEW.version_id AND status IN ('published','retired')) THEN
   RAISE EXCEPTION 'Cannot change component authority after publishing'; END IF;

 -- Geçersiz kılma: aynı kapsam, tek sefer, canlı kayıtta kullanılmıyor olmalı
 IF NEW.supersedes_decision_id IS NOT NULL THEN
   IF NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d WHERE d.id = NEW.supersedes_decision_id
      AND d.version_id = NEW.version_id AND d.grade_id IS NOT DISTINCT FROM NEW.grade_id) THEN
     RAISE EXCEPTION 'Superseded decision scope mismatch'; END IF;
   IF EXISTS (SELECT 1 FROM public.curriculum_versions v WHERE v.component_authority_decision_id = NEW.supersedes_decision_id)
      OR EXISTS (SELECT 1 FROM public.curriculum_outcomes o WHERE NEW.supersedes_decision_id IN (o.verification_decision_id, o.component_structure_decision_id))
      OR EXISTS (SELECT 1 FROM public.curriculum_components c WHERE c.verification_decision_id = NEW.supersedes_decision_id)
      OR EXISTS (SELECT 1 FROM public.curriculum_theme_outcomes t WHERE t.mapping_decision_id = NEW.supersedes_decision_id)
      OR EXISTS (SELECT 1 FROM public.curriculum_theme_components t WHERE NEW.supersedes_decision_id IN (t.mapping_decision_id, t.split_decision_id))
      OR EXISTS (SELECT 1 FROM public.curriculum_grades g WHERE NEW.supersedes_decision_id IN (g.expected_outcome_count_decision_id, g.expected_theme_count_decision_id)) THEN
     RAISE EXCEPTION 'Cannot supersede a decision still referenced by live records'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER curriculum_decision_guard BEFORE INSERT ON public.curriculum_review_decisions
 FOR EACH ROW EXECUTE FUNCTION public.curriculum_guard_decision();

-- ===================== Satır koruması (değişmezlik, kanıt, ayrım) =====================
CREATE OR REPLACE FUNCTION public.curriculum_guard_rows() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE gid uuid; state text; parent_state text; src text; r_label text; r_code text;
BEGIN
 IF TG_TABLE_NAME IN ('curriculum_source_documents','curriculum_import_batches','curriculum_import_rows','curriculum_review_decisions') THEN
   RAISE EXCEPTION 'Append-only table';
 END IF;
 IF TG_OP = 'DELETE' THEN
   IF TG_TABLE_NAME IN ('curriculum_outcomes','curriculum_themes','curriculum_theme_outcomes') THEN gid := OLD.grade_id;
   ELSIF TG_TABLE_NAME = 'curriculum_components' THEN SELECT grade_id INTO gid FROM public.curriculum_outcomes WHERE id = OLD.outcome_id;
   ELSIF TG_TABLE_NAME = 'curriculum_theme_components' THEN SELECT grade_id INTO gid FROM public.curriculum_theme_outcomes WHERE id = OLD.theme_outcome_id; END IF;
   SELECT status INTO state FROM public.curriculum_grades WHERE id = gid FOR UPDATE;
   IF state IN ('published','retired') THEN RAISE EXCEPTION 'Published/retired curriculum is immutable'; END IF;
   RETURN OLD;
 END IF;

 IF TG_TABLE_NAME IN ('curriculum_outcomes','curriculum_themes','curriculum_theme_outcomes') THEN gid := NEW.grade_id;
 ELSIF TG_TABLE_NAME = 'curriculum_components' THEN SELECT grade_id INTO gid FROM public.curriculum_outcomes WHERE id = NEW.outcome_id;
 ELSIF TG_TABLE_NAME = 'curriculum_theme_components' THEN SELECT grade_id INTO gid FROM public.curriculum_theme_outcomes WHERE id = NEW.theme_outcome_id; END IF;
 SELECT status INTO state FROM public.curriculum_grades WHERE id = gid FOR UPDATE;
 IF state IN ('published','retired') THEN RAISE EXCEPTION 'Published/retired curriculum is immutable'; END IF;

 IF TG_OP = 'UPDATE' THEN
  IF TG_TABLE_NAME = 'curriculum_outcomes' THEN IF (NEW.canonical_code, NEW.canonical_text, NEW.code_key, NEW.source_document_id, NEW.source_page, NEW.grade_id, NEW.version_id, NEW.learning_area_id)
     IS DISTINCT FROM (OLD.canonical_code, OLD.canonical_text, OLD.code_key, OLD.source_document_id, OLD.source_page, OLD.grade_id, OLD.version_id, OLD.learning_area_id) THEN
     RAISE EXCEPTION 'Canonical outcome immutable'; END IF; END IF;
  IF TG_TABLE_NAME = 'curriculum_components' THEN IF (NEW.canonical_label, NEW.canonical_text, NEW.label_key, NEW.source_document_id, NEW.source_page, NEW.outcome_id)
     IS DISTINCT FROM (OLD.canonical_label, OLD.canonical_text, OLD.label_key, OLD.source_document_id, OLD.source_page, OLD.outcome_id) THEN
     RAISE EXCEPTION 'Canonical component immutable'; END IF; END IF;
  IF TG_TABLE_NAME = 'curriculum_themes' THEN IF (NEW.published_name, NEW.theme_no, NEW.source_document_id, NEW.grade_id, NEW.version_id)
     IS DISTINCT FROM (OLD.published_name, OLD.theme_no, OLD.source_document_id, OLD.grade_id, OLD.version_id) THEN
     RAISE EXCEPTION 'Theme source immutable'; END IF; END IF;
  IF TG_TABLE_NAME = 'curriculum_theme_outcomes' THEN IF (NEW.published_code, NEW.published_text, NEW.published_code_key, NEW.import_row_id, NEW.source_field, NEW.source_document_id, NEW.source_page, NEW.theme_id, NEW.grade_id, NEW.version_id)
     IS DISTINCT FROM (OLD.published_code, OLD.published_text, OLD.published_code_key, OLD.import_row_id, OLD.source_field, OLD.source_document_id, OLD.source_page, OLD.theme_id, OLD.grade_id, OLD.version_id) THEN
     RAISE EXCEPTION 'Theme outcome source immutable'; END IF; END IF;
  IF TG_TABLE_NAME = 'curriculum_theme_components' THEN IF (NEW.published_label, NEW.published_text, NEW.published_label_key, NEW.import_row_id, NEW.source_field, NEW.origin, NEW.segment_no, NEW.segment_start, NEW.segment_end, NEW.split_decision_id, NEW.theme_outcome_id, NEW.theme_id)
     IS DISTINCT FROM (OLD.published_label, OLD.published_text, OLD.published_label_key, OLD.import_row_id, OLD.source_field, OLD.origin, OLD.segment_no, OLD.segment_start, OLD.segment_end, OLD.split_decision_id, OLD.theme_outcome_id, OLD.theme_id) THEN
     RAISE EXCEPTION 'Theme component source immutable'; END IF; END IF;
 END IF;

 IF TG_TABLE_NAME = 'curriculum_outcomes' THEN
   IF NEW.verification_status = 'verified' AND NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d
      WHERE d.id = NEW.verification_decision_id AND d.outcome_id = NEW.id AND d.decision = 'verify_canonical') THEN
     RAISE EXCEPTION 'Outcome verification requires matching decision'; END IF;
   IF NEW.component_structure = 'no_components_confirmed' THEN
     IF NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d WHERE d.id = NEW.component_structure_decision_id
        AND d.outcome_id = NEW.id AND d.decision = 'confirm_no_components') THEN
       RAISE EXCEPTION 'No-component claim requires matching decision'; END IF;
     IF EXISTS (SELECT 1 FROM public.curriculum_components WHERE outcome_id = NEW.id) THEN RAISE EXCEPTION 'Outcome has components'; END IF;
   END IF;
 END IF;

 IF TG_TABLE_NAME = 'curriculum_components' THEN
   IF EXISTS (SELECT 1 FROM public.curriculum_outcomes WHERE id = NEW.outcome_id AND component_structure = 'no_components_confirmed') THEN
     RAISE EXCEPTION 'Outcome confirmed to have no components'; END IF;
   IF NEW.verification_status = 'verified' AND NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d
      WHERE d.id = NEW.verification_decision_id AND d.component_id = NEW.id AND d.decision = 'verify_canonical') THEN
     RAISE EXCEPTION 'Component verification requires matching decision'; END IF;
 END IF;

 IF TG_TABLE_NAME = 'curriculum_theme_outcomes' THEN
   IF TG_OP = 'INSERT' THEN
     SELECT r.raw_values ->> NEW.source_field, r.published_code INTO src, r_code FROM public.curriculum_import_rows r WHERE r.id = NEW.import_row_id;
     IF src IS DISTINCT FROM NEW.published_text THEN RAISE EXCEPTION 'Theme outcome text must equal original source field'; END IF;
     IF r_code IS DISTINCT FROM NEW.published_code THEN RAISE EXCEPTION 'Theme outcome code must equal source row code'; END IF;
   END IF;
   IF TG_OP = 'UPDATE' AND OLD.mapping_status = 'excluded' AND NEW.mapping_status <> 'excluded' THEN
     RAISE EXCEPTION 'Excluded parent cannot be reopened in place'; END IF;
   IF NEW.mapping_status IN ('verified','excluded') AND NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d
      WHERE d.id = NEW.mapping_decision_id AND d.theme_outcome_id = NEW.id
        AND d.decision = CASE WHEN NEW.mapping_status = 'verified' THEN 'map_to_canonical' ELSE 'exclude' END
        AND (NEW.mapping_status = 'excluded' OR d.target_outcome_id = NEW.outcome_id)) THEN
     RAISE EXCEPTION 'Incorrect outcome mapping/exclusion decision'; END IF;
 END IF;

 IF TG_TABLE_NAME = 'curriculum_theme_components' THEN
   SELECT mapping_status INTO parent_state FROM public.curriculum_theme_outcomes WHERE id = NEW.theme_outcome_id;
   IF NEW.excluded_by_parent AND parent_state <> 'excluded' THEN RAISE EXCEPTION 'Parent exclusion required'; END IF;
   IF NEW.mapping_status = 'verified' AND parent_state <> 'verified' THEN RAISE EXCEPTION 'Parent outcome must be verified'; END IF;
   IF TG_OP = 'INSERT' THEN
     -- Aynı kaynak satırı/alanı üzerinde eşzamanlı ayrım düzenlemelerini sıraya koy.
     PERFORM pg_advisory_xact_lock(hashtextextended(NEW.import_row_id::text || '|' || NEW.source_field, 0));
     SELECT r.raw_values ->> NEW.source_field, r.published_label INTO src, r_label FROM public.curriculum_import_rows r WHERE r.id = NEW.import_row_id;
     IF src IS NULL THEN RAISE EXCEPTION 'Source field not found in original row'; END IF;
     IF NEW.origin = 'source_row' THEN
       IF src <> NEW.published_text THEN RAISE EXCEPTION 'Theme component text must equal original source field'; END IF;
       IF r_label IS DISTINCT FROM NEW.published_label THEN RAISE EXCEPTION 'Theme component label must equal source row label'; END IF;
       IF EXISTS (SELECT 1 FROM public.curriculum_theme_components c WHERE c.import_row_id = NEW.import_row_id
          AND c.source_field = NEW.source_field AND c.origin = 'split_by_decision') THEN
         RAISE EXCEPTION 'Cannot mix full row with split segments'; END IF;
     ELSE
       IF NEW.segment_end > char_length(src)
          OR substring(src FROM NEW.segment_start + 1 FOR NEW.segment_end - NEW.segment_start) <> NEW.published_text THEN
         RAISE EXCEPTION 'Split text is not the exact original source segment'; END IF;
       IF NOT EXISTS (SELECT 1 FROM public.curriculum_review_decisions d WHERE d.id = NEW.split_decision_id
          AND d.decision = 'split_source_row' AND d.import_row_id = NEW.import_row_id) THEN
         RAISE EXCEPTION 'Split decision must reference same source row'; END IF;
       IF EXISTS (SELECT 1 FROM public.curriculum_theme_components c WHERE c.import_row_id = NEW.import_row_id
          AND c.source_field = NEW.source_field
          AND (c.origin = 'source_row' OR int4range(c.segment_start, c.segment_end, '[)') && int4range(NEW.segment_start, NEW.segment_end, '[)'))) THEN
         RAISE EXCEPTION 'Overlapping or mixed source segments'; END IF;
     END IF;
   END IF;
   IF NEW.mapping_status IN ('verified','excluded') AND NOT NEW.excluded_by_parent AND NOT EXISTS (
      SELECT 1 FROM public.curriculum_review_decisions d
      WHERE d.id = NEW.mapping_decision_id AND d.theme_component_id = NEW.id
        AND d.decision = CASE WHEN NEW.mapping_status = 'verified' THEN 'map_to_canonical' ELSE 'exclude' END
        AND (NEW.mapping_status = 'excluded' OR d.target_component_id = NEW.component_id)) THEN
     RAISE EXCEPTION 'Incorrect component mapping/exclusion decision'; END IF;
 END IF;
 RETURN NEW;
END $$;

-- Üst tema kazanımı dışlanınca alt bileşenler aynı işlemde dışlanır (ertelenmiş FK sayesinde sıralama sorunu yok).
CREATE OR REPLACE FUNCTION public.curriculum_cascade_parent_exclusion() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
 IF NEW.mapping_status = 'excluded' AND OLD.mapping_status IS DISTINCT FROM 'excluded' THEN
   UPDATE public.curriculum_theme_components
      SET mapping_status = 'excluded', excluded_by_parent = true, outcome_id = NULL, component_id = NULL, mapping_decision_id = NULL
    WHERE theme_outcome_id = NEW.id AND mapping_status <> 'excluded';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER curriculum_parent_exclusion AFTER UPDATE OF mapping_status ON public.curriculum_theme_outcomes
 FOR EACH ROW EXECUTE FUNCTION public.curriculum_cascade_parent_exclusion();

